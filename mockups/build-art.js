// Bundles the art listed in apps/deutsch/art/manifest.json into mockups/art-bundle.js (const ART = { id: '<svg…>' }),
// checking the rules the spec's tests will enforce. Run: node mockups/build-art.js
// This is the prototype of the spec's `npm run art`; it writes only into mockups/.
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'apps/deutsch/art/manifest.json'), 'utf8'));
const SIZE = { plate: '0 0 1600 900', cast: '0 0 240 360', word: '0 0 120 120', icon: '0 0 64 64', event: '0 0 160 160', stamp: '0 0 160 160', mouth: '0 0 120 120', empty: '0 0 120 120' };
const MOODS = ['neutral', 'pleased', 'thinking', 'amused', 'surprised'];
const errors = [], ART = {};
for (const a of manifest) {
  const file = path.join(root, a.file);
  if (!fs.existsSync(file)) { errors.push(`${a.id}: missing file ${a.file}`); continue; }
  const svg = fs.readFileSync(file, 'utf8').trim();
  if (/#[0-9a-f]{3,8}\b/i.test(svg.replace(/href="#[^"]+"/g, ''))) errors.push(`${a.id}: hex colour in ${a.file}`);
  const vb = (svg.match(/viewBox="([^"]+)"/) || [])[1];
  if (vb !== SIZE[a.kind]) errors.push(`${a.id}: viewBox ${vb}, expected ${SIZE[a.kind]}`);
  if (!/--il-hi\b/.test(svg) && !['mouth', 'stamp'].includes(a.kind)) errors.push(`${a.id}: no --il-hi highlight`);
  if (a.kind === 'cast') MOODS.forEach(m => { if (!svg.includes(`data-mood="${m}"`)) errors.push(`${a.id}: no ${m} face`); });
  ART[a.id] = svg.replace(/\s*\n\s*/g, '');
}
const listed = new Set(manifest.map(a => a.file));
for (const dir of ['shared/art/cast', 'shared/art/events', 'shared/art/empty', 'apps/deutsch/art/plates', 'apps/deutsch/art/words', 'apps/deutsch/art/icons', 'apps/deutsch/art/mouth'])
  for (const f of fs.readdirSync(path.join(root, dir))) if (f.endsWith('.svg') && !listed.has(dir + '/' + f)) errors.push(`${dir}/${f} has no manifest entry`);
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }
const out = '/* generated by mockups/build-art.js from apps/deutsch/art/manifest.json; do not edit */\nconst ART_MANIFEST = ' + JSON.stringify(manifest) + ';\nconst ART = ' + JSON.stringify(ART, null, 0) + ';\n';
fs.writeFileSync(path.join(__dirname, 'art-bundle.js'), out);
console.log(`art-bundle.js: ${Object.keys(ART).length} assets, ${(out.length / 1024).toFixed(1)} KB`);
