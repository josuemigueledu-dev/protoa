// `npm run art`: checks every file in apps/deutsch/art/manifest.json and writes apps/deutsch/js/art-bundle.js
// (and the copy the mockups load). `npm run art -- --check` checks only and fails if the bundle is stale.
// Exports checkArt/renderBundle so server/test/art.test.js runs the same rules.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
export const BUNDLE_FILES = ['apps/deutsch/js/art-bundle.js', 'mockups/art-bundle.js'];
export const SIZE = { plate: '0 0 1600 900', cast: '0 0 240 360', word: '0 0 120 120', icon: '0 0 64 64', event: '0 0 160 160', stamp: '0 0 160 160', mouth: '0 0 120 120', empty: '0 0 120 120' };
export const MOODS = ['neutral', 'pleased', 'thinking', 'amused', 'surprised'];
const NO_HIGHLIGHT = ['mouth', 'stamp'];
const DIRS = ['shared/art/cast', 'shared/art/events', 'shared/art/empty', 'apps/deutsch/art/plates', 'apps/deutsch/art/words', 'apps/deutsch/art/icons', 'apps/deutsch/art/mouth'];

export const readManifest = () => JSON.parse(fs.readFileSync(path.join(root, 'apps/deutsch/art/manifest.json'), 'utf8'));

// Returns { errors, ART }; errors is a list of readable strings.
export function checkArt(manifest = readManifest()) {
  const errors = [], ART = {}, ids = new Set();
  for (const a of manifest) {
    if (ids.has(a.id)) errors.push(`${a.id}: duplicate id`);
    ids.add(a.id);
    if (!(a.kind in SIZE)) { errors.push(`${a.id}: unknown kind ${a.kind}`); continue; }
    const file = path.join(root, a.file);
    if (!fs.existsSync(file)) { errors.push(`${a.id}: missing file ${a.file}`); continue; }
    const svg = fs.readFileSync(file, 'utf8').trim();
    if (/#[0-9a-f]{3,8}\b/i.test(svg.replace(/href="#[^"]+"/g, ''))) errors.push(`${a.id}: hex colour in ${a.file}`);
    const vb = (svg.match(/viewBox="([^"]+)"/) || [])[1];
    if (vb !== SIZE[a.kind]) errors.push(`${a.id}: viewBox ${vb}, expected ${SIZE[a.kind]}`);
    if (!/--il-hi\b/.test(svg) && !NO_HIGHLIGHT.includes(a.kind)) errors.push(`${a.id}: no --il-hi highlight`);
    if (a.kind === 'cast') for (const m of MOODS) if (!svg.includes(`data-mood="${m}"`)) errors.push(`${a.id}: no ${m} face`);
    ART[a.id] = svg.replace(/\s*\n\s*/g, '');
  }
  const listed = new Set(manifest.map(a => a.file));
  for (const dir of DIRS)
    for (const f of fs.readdirSync(path.join(root, dir))) if (f.endsWith('.svg') && !listed.has(`${dir}/${f}`)) errors.push(`${dir}/${f} has no manifest entry`);
  return { errors, ART };
}

export const renderBundle = (manifest, ART) =>
  '/* generated by `npm run art` (scripts/art.mjs) from apps/deutsch/art/manifest.json; do not edit */\n' +
  `const ART_MANIFEST = ${JSON.stringify(manifest)};\nconst ART = ${JSON.stringify(ART)};\n`;

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const manifest = readManifest();
  const { errors, ART } = checkArt(manifest);
  if (errors.length) { console.error(errors.join('\n')); process.exit(1); }
  const out = renderBundle(manifest, ART);
  if (process.argv.includes('--check')) {
    const stale = BUNDLE_FILES.filter(f => !fs.existsSync(path.join(root, f)) || fs.readFileSync(path.join(root, f), 'utf8') !== out);
    if (stale.length) { console.error(`stale, run npm run art: ${stale.join(', ')}`); process.exit(1); }
    console.log('art ok');
  } else {
    for (const f of BUNDLE_FILES) fs.writeFileSync(path.join(root, f), out);
    console.log(`art-bundle.js: ${Object.keys(ART).length} assets, ${(out.length / 1024).toFixed(1)} KB`);
  }
}
